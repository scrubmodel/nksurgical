import { createClient } from 'https://cdn.jsdelivr.net/npm/@supabase/supabase-js@2/+esm';
import { SUPABASE_URL, SUPABASE_ANON_KEY } from './config.js';

// Sessions persist in localStorage and auto-refresh indefinitely — a login
// stays valid until the user explicitly signs out (no forced timeout is
// configured on the Supabase project either), so closing/reopening the app
// does not log the user out.
export const supabase = createClient(SUPABASE_URL, SUPABASE_ANON_KEY, {
  auth: {
    persistSession: true,
    autoRefreshToken: true,
    detectSessionInUrl: true,
    storage: window.localStorage,
  },
});
